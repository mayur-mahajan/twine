//! `twine font`: argument parsing into typed values and the command end to end (needs
//! `assets/fonts/Montserrat-Medium.ttf`).

use std::path::{Path, PathBuf};

use clap::Parser;
use twine_build::font::{Gamma, Hinting};
use twine_cli::font::{CharRanges, FontArgs, font_from_args};
use twine_text::Bpp;

#[derive(Parser)]
struct Wrap {
    #[command(flatten)]
    args: FontArgs,
}

const BASE: [&str; 9] = [
    "twine", "--ttf", "a.ttf", "--size", "14", "--name", "X", "--out", "x.rs",
];

fn one(r: std::ops::RangeInclusive<char>) -> Vec<std::ops::RangeInclusive<char>> {
    std::iter::once(r).collect()
}

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

#[test]
fn bpp_is_validated_when_parsed() {
    for (ok, bpp) in [
        ("1", Bpp::One),
        ("2", Bpp::Two),
        ("4", Bpp::Four),
        ("8", Bpp::Eight),
    ] {
        let w = Wrap::try_parse_from(BASE.iter().copied().chain(["--bpp", ok])).unwrap();
        assert_eq!(w.args.bpp, bpp);
    }
    assert_eq!(Wrap::try_parse_from(BASE).unwrap().args.bpp, Bpp::Four, "default");
    for bad in ["3", "0", "16", "x"] {
        let e = Wrap::try_parse_from(BASE.iter().copied().chain(["--bpp", bad]))
            .err()
            .unwrap();
        assert!(e.to_string().contains("bpp"), "{e}");
    }
}

/// R6.S03: `--hinting` and `--gamma` are typed when parsed, with the generator's defaults.
#[test]
fn hinting_and_gamma_are_typed_when_parsed() {
    let w = Wrap::try_parse_from(BASE).unwrap();
    assert_eq!((w.args.hinting, w.args.gamma), (Hinting::Full, Gamma::DEFAULT));
    let w = Wrap::try_parse_from(
        BASE.iter()
            .copied()
            .chain(["--hinting", "light", "--gamma", "1.3,2"]),
    )
    .unwrap();
    assert_eq!(
        (w.args.hinting, w.args.gamma),
        (Hinting::Light, Gamma::new(130, 200))
    );
    let f = font_from_args(&w.args).unwrap().chars_from('A');
    assert!(f.command_line().contains("--hinting light --gamma 1.30,2.00"));
    let w = Wrap::try_parse_from(
        BASE.iter()
            .copied()
            .chain(["--hinting", "none", "--gamma", "linear"]),
    )
    .unwrap();
    assert_eq!((w.args.hinting, w.args.gamma), (Hinting::None, Gamma::LINEAR));
    for (opt, bad) in [("--hinting", "strong"), ("--gamma", "1.2")] {
        let e = Wrap::try_parse_from(BASE.iter().copied().chain([opt, bad]))
            .err()
            .unwrap();
        assert!(e.to_string().contains(&opt[2..]), "{e}");
    }
}

#[test]
fn ranges_are_typed_when_parsed() {
    let w = Wrap::try_parse_from(BASE.iter().copied().chain([
        "--range",
        "0x41-0x43",
        "--range",
        "68",
        "--range",
        "chars:°A",
    ]))
    .unwrap();
    assert_eq!(
        w.args.ranges,
        [
            CharRanges(one('A'..='C')),
            CharRanges(one('D'..='D')),
            CharRanges(vec!['A'..='A', '°'..='°'])
        ]
    );
    let f = font_from_args(&w.args).unwrap();
    assert_eq!(f.chars().iter().collect::<String>(), "ABCD°");
    assert!(Wrap::try_parse_from(BASE.iter().copied().chain(["--range", "0x7F-0x20"])).is_err());
}

#[test]
fn command_writes_the_font_its_header_reproduces() {
    let dir = std::env::temp_dir().join(format!("twine-cli-font-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let out = dir.join("f.rs");
    let st = std::process::Command::new(env!("CARGO_BIN_EXE_twine"))
        .current_dir(root())
        .args([
            "font",
            "--ttf",
            "assets/fonts/Montserrat-Medium.ttf",
            "--size",
            "12",
            "--bpp",
            "2",
            "--range",
            "0x30-0x39",
            "--symbols",
            "fa",
            "--compress",
            "--name",
            "DIGITS",
            "--out",
        ])
        .arg(&out)
        .status()
        .unwrap();
    assert!(st.success());
    let src = std::fs::read_to_string(&out).unwrap();
    assert!(src.starts_with(
        "// Generated by twine-build 0.1.0: twine font --ttf assets/fonts/Montserrat-Medium.ttf --size 12 --bpp 2 --range 0x30-0x39 --symbols fa --symbols-ttf assets/fonts/fa-solid-900.ttf --symbols-ttf assets/fonts/fa-brands-400.ttf --compress --name DIGITS\n"
    ));
    assert!(src.contains("bpp: twine_text::Bpp::Two,"));
    assert!(src.contains("format: twine_text::BitmapFormat::Compressed,"));
    let dump = std::process::Command::new(env!("CARGO_BIN_EXE_twine"))
        .current_dir(root())
        .args([
            "font",
            "--size",
            "14",
            "--dump",
            "assets/fonts/Montserrat-Medium.ttf",
            "--chars",
            "A",
        ])
        .output()
        .unwrap();
    assert!(String::from_utf8_lossy(&dump.stdout).contains("U+0041 'A'"));
    let _ = std::fs::remove_dir_all(&dir);
}
