/// Every `macro_rules!` definition of the product code.
#[must_use]
pub fn macros(files: &[SourceFile]) -> Vec<MacroDef> {
    struct Defs<'a> {
        file: &'a SourceFile,
        out: Vec<MacroDef>,
    }
    impl<'ast> Visit<'ast> for Defs<'_> {
        fn visit_item_mod(&mut self, m: &'ast syn::ItemMod) {
            if !is_test_cfg(&m.attrs) {
                visit::visit_item_mod(self, m);
            }
        }
        fn visit_item_fn(&mut self, f: &'ast syn::ItemFn) {
            if !is_test_cfg(&f.attrs) {
                visit::visit_item_fn(self, f);
            }
        }
        fn visit_item_macro(&mut self, m: &'ast syn::ItemMacro) {
            if is_test_cfg(&m.attrs) || !m.mac.path.is_ident("macro_rules") {
                return;
            }
            let Some(name) = &m.ident else { return };
            let krate = &self.file.krate;
            self.out.push(MacroDef {
                krate: krate.clone(),
                name: name.to_string(),
                file: self
                    .file
                    .rel
                    .strip_prefix(&format!("crates/{krate}/"))
                    .unwrap_or(&self.file.rel)
                    .to_owned(),
                exported: m.attrs.iter().any(|a| a.path().is_ident("macro_export")),
                unqualified: unqualified(&m.mac.tokens),
            });
        }
    }
    let mut out = Vec::new();
    for file in files {
        let Ok(ast) = syn::parse_file(&file.src) else {
            continue;
        };
        let mut v = Defs {
            file,
            out: Vec::new(),
        };
        v.visit_file(&ast);
        out.extend(v.out);
    }
    out.sort();
    out
}

/// The names a `macro_rules!` body's transcribers use without a path (G12): prelude names not
/// preceded by `::`, `crate` not preceded by `$` (`crate::` instead of `$crate::`), and paths
/// that start with a crate name (`twine_core::`) without a leading `::`.
#[must_use]
pub fn unqualified(body: &TokenStream) -> BTreeSet<String> {
    // Rules are `(matcher) => {transcriber};`: the group after each `=>`.
    let tokens: Vec<TokenTree> = body.clone().into_iter().collect();
    let mut out = BTreeSet::new();
    for w in tokens.windows(3) {
        if let (TokenTree::Punct(a), TokenTree::Punct(b), TokenTree::Group(g)) = (&w[0], &w[1], &w[2])
            && a.as_char() == '='
            && b.as_char() == '>'
        {
            scan_transcriber(g.stream(), &mut out);
        }
    }
    out
}

fn scan_transcriber(ts: TokenStream, out: &mut BTreeSet<String>) {
    let tokens: Vec<TokenTree> = ts.into_iter().collect();
    for (i, t) in tokens.iter().enumerate() {
        match t {
            TokenTree::Group(g) => scan_transcriber(g.stream(), out),
            TokenTree::Ident(id) => {
                let name = id.to_string();
                let prev = i.checked_sub(1).and_then(|j| tokens.get(j));
                let prev2 = i.checked_sub(2).and_then(|j| tokens.get(j));
                let after_path_sep = matches!((prev2, prev), (Some(TokenTree::Punct(a)), Some(TokenTree::Punct(b))) if a.as_char() == ':' && b.as_char() == ':');
                let after_dollar = matches!(prev, Some(TokenTree::Punct(p)) if p.as_char() == '$');
                let after_dot = matches!(prev, Some(TokenTree::Punct(p)) if p.as_char() == '.');
                let next_is_path_sep = matches!(tokens.get(i + 1), Some(TokenTree::Punct(p)) if p.as_char() == ':')
                    && matches!(tokens.get(i + 2), Some(TokenTree::Punct(p)) if p.as_char() == ':');
                if after_path_sep || after_dollar || after_dot {
                    continue;
                }
                if PRELUDE.contains(&name.as_str()) {
                    out.insert(name);
                } else if name == "crate" && next_is_path_sep {
                    out.insert("crate::".to_owned());
                } else if name.starts_with("twine_") && next_is_path_sep {
                    out.insert(format!("{name}::"));
                }
            }
            _ => {}
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn file(rel: &str, src: &str) -> SourceFile {
        SourceFile {
            krate: "k".into(),
            rel: rel.into(),
            src: src.into(),
        }
    }

    #[test]
    fn finds_direct_and_mutual_recursion() {
        let a = file(
            "crates/k/src/a.rs",
            "fn fact(n: u32) -> u32 { if n == 0 { 1 } else { n * fact(n - 1) } }
             fn ping(n: u32) { if n > 0 { crate::b::pong(n - 1) } }
             fn leaf() {}
             struct T;
             impl T { fn walk(&self) { self.walk(); leaf(); } fn up(&self) { Self::down() } fn down() { T::up_free() } fn up_free() {} }
             #[cfg(test)] mod tests { fn t() { t() } }",
        );
        let b = file("crates/k/src/b.rs", "pub fn pong(n: u32) { super::a::ping(n) }");
        let found: Vec<Vec<String>> = recursion(&[a, b]).into_iter().map(|c| c.functions).collect();
        assert_eq!(
            found,
            vec![
                vec!["T::walk".to_owned()],
                vec!["a::fact".to_owned()],
                vec!["a::ping".to_owned(), "b::pong".to_owned()],
            ]
        );
    }

    #[test]
    fn finds_unqualified_names_in_transcribers() {
        let f = file(
            "crates/k/src/lib.rs",
            "#[macro_export]
             macro_rules! good { ($e:expr) => { ::core::option::Option::Some($e) }; }
             macro_rules! bad { ($e:expr) => { Some($e).map(Into::into).unwrap_or(crate::X) }; }
             macro_rules! ext { () => { twine_core::f() }; }
             macro_rules! dot { ($e:expr) => { $e.clone() }; }",
        );
        let defs = macros(&[f]);
        let by: BTreeMap<&str, (&BTreeSet<String>, bool)> = defs
            .iter()
            .map(|d| (d.name.as_str(), (&d.unqualified, d.exported)))
            .collect();
        assert!(by["good"].0.is_empty() && by["good"].1);
        assert_eq!(
            by["bad"].0.iter().map(String::as_str).collect::<Vec<_>>(),
            ["Into", "Some", "crate::"]
        );
        assert_eq!(
            by["ext"].0.iter().map(String::as_str).collect::<Vec<_>>(),
            ["twine_core::"]
        );
        assert!(by["dot"].0.is_empty());
    }

    #[test]
    fn block_is_replaced_between_markers() {
        let doc = format!("# R\n\ntext\n\n{BEGIN}\nold\n{END}\n\nmore\n");
        let new = replace_block(&doc, &format!("{BEGIN}\nnew\n{END}")).unwrap();
        assert_eq!(new, format!("# R\n\ntext\n\n{BEGIN}\nnew\n{END}\n\nmore\n"));
        assert_eq!(replace_block("no block", "x"), None);
    }
}
