//! `cargo xtask guidelines [--check]`: upkeep of the coding-guidelines deviation register
//! ([`REGISTER`], `docs/safety/coding-guidelines-deviations.md`).
//!
//! Measures the guidelines that a source scan can measure, over the register's **product
//! code** (the library crates under `crates/` except the test and host tooling
//! [`NOT_PRODUCT`]; `#[cfg(test)]` code left out), and rewrites the generated block of the
//! register (between [`BEGIN`] and [`END`]):
//!
//! - **G1** recursion: functions that call themselves, directly or through other functions of
//!   the same crate (a by-name call graph: free functions resolved by module path or a unique
//!   name, methods through `self.f(..)` / `Self::f(..)` / `Type::f(..)`; calls through trait
//!   objects or on other receivers are not followed, so indirect recursion through them is not
//!   found — the register lists those by hand);
//! - **G3**/**G4** divisions: the divisor audit of `cargo xtask divisions` (G3: every divisor
//!   that is not a literal is non-zero by type, guard or proof; G4: integer divisions);
//! - **G5**/**G6** shifts: the shift audit of `cargo xtask shifts`;
//! - **G11** `macro_rules!` definitions (and how many are `#[macro_export]`ed);
//! - **G12** macros whose transcribers use prelude names (`Option`, `Some`, `Into`, …) without
//!   a path, `crate::` instead of `$crate::`, or a crate path without a leading `::`.
//!
//! `--check` (CI stage `guidelines`, job `evidence`) fails when the block is out of date or a
//! shift or divisor lacks its proof. The register's prose (impact, resolution) is written by
//! hand; the block holds the numbers and lists it cites. Without the register (a checkout
//! without `docs/`) only the audits are checked.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use proc_macro2::{TokenStream, TokenTree};
use syn::visit::{self, Visit};

use crate::cmd::audit::{self, SourceFile, is_test_cfg};
use crate::cmd::{divisions, shifts};
use crate::util::{R, workspace_root};

/// The register.
pub const REGISTER: &str = "docs/safety/coding-guidelines-deviations.md";

/// Start of the generated block.
pub const BEGIN: &str = "<!-- BEGIN generated by `cargo xtask guidelines`; do not edit by hand -->";

/// End of the generated block.
pub const END: &str = "<!-- END generated by `cargo xtask guidelines` -->";

/// Crates that are not product code (register § 2): test and host tooling.
pub const NOT_PRODUCT: &[&str] = &["twine-testing", "twine-sim", "twine-demos"];

/// Whether `krate` is product code.
fn is_product(krate: &str) -> bool {
    !NOT_PRODUCT.contains(&krate)
}

/// `cargo xtask guidelines [--check]`.
pub fn run(check: bool) -> R {
    let files: Vec<SourceFile> = audit::library_files()?
        .into_iter()
        .filter(|f| is_product(&f.krate))
        .collect();
    let mut errors = Vec::new();

    let (_, shift_sites) = shifts::sites()?;
    let shift_sites: Vec<shifts::Proven> = shift_sites
        .into_iter()
        .filter(|p| is_product(&p.site.krate))
        .collect();
    let (_, div_sites) = divisions::sites()?;
    let div_sites: Vec<divisions::Proven> = div_sites
        .into_iter()
        .filter(|p| is_product(&p.site.krate))
        .collect();
    let shift_missing = shift_sites
        .iter()
        .filter(|p| p.site.kind.needs_proof() && p.proof.is_none())
        .count();
    let div = divisions::Counts::of(&div_sites, None);
    if shift_missing > 0 {
        errors.push(format!(
            "{shift_missing} shift(s) without a `// SHIFT:` proof (run `cargo xtask shifts`)"
        ));
    }
    if div.missing > 0 {
        errors.push(format!(
            "{} division(s) without a non-zero proof (run `cargo xtask divisions`)",
            div.missing
        ));
    }

    let m = Measures {
        recursion: recursion(&files),
        macros: macros(&files),
        shifts: shift_counts(&shift_sites),
        div,
    };
    let block = render(&m);
    let path = workspace_root().join(REGISTER);
    match std::fs::read_to_string(&path) {
        Ok(current) => match replace_block(&current, &block) {
            Some(updated) if updated != current => {
                if check {
                    errors.push(format!(
                        "{REGISTER}: the generated block is out of date (run `cargo xtask guidelines` and review the change)"
                    ));
                } else {
                    std::fs::write(&path, updated)?;
                    println!("guidelines: {REGISTER} updated");
                }
            }
            Some(_) => {}
            None => errors.push(format!("{REGISTER}: no generated block ({BEGIN} … {END})")),
        },
        Err(_) => println!("guidelines: note: {REGISTER} not found; only the audits are checked"),
    }
    if errors.is_empty() {
        println!(
            "guidelines: ok (G1 {} recursive functions in {} cycles; G3 {} non-constant divisors proven; G5 {} run-time shifts proven, {} constant; G11 {} macros; G12 {} macros with unqualified names)",
            m.recursion.iter().map(|c| c.functions.len()).sum::<usize>(),
            m.recursion.len(),
            div.nonzero + div.guarded + div.proven,
            m.shifts.0,
            m.shifts.1,
            m.macros.len(),
            m.macros.iter().filter(|d| !d.unqualified.is_empty()).count()
        );
        Ok(())
    } else {
        for e in &errors {
            println!("guidelines: {e}");
        }
        Err(format!("guidelines: {} problem(s)", errors.len()).into())
    }
}

/// Everything the block reports.
#[derive(Debug)]
pub struct Measures {
    /// G1: recursion cycles.
    pub recursion: Vec<Cycle>,
    /// G11/G12: `macro_rules!` definitions.
    pub macros: Vec<MacroDef>,
    /// G5: shifts by a run-time amount, by a named constant (all with proofs when the audit
    /// passes).
    pub shifts: (usize, usize),
    /// G3/G4: divisions.
    pub div: divisions::Counts,
}

/// Run-time and constant shift amounts.
fn shift_counts(sites: &[shifts::Proven]) -> (usize, usize) {
    let of = |k| sites.iter().filter(|p| p.site.kind == k).count();
    (of(audit::Operand::Runtime), of(audit::Operand::Const))
}

/// Replaces the generated block of `doc` (`None` without one).
#[must_use]
pub fn replace_block(doc: &str, block: &str) -> Option<String> {
    let start = doc.find(BEGIN)?;
    let end = doc[start..].find(END)? + start + END.len();
    Some(format!("{}{}{}", &doc[..start], block, &doc[end..]))
}

/// The generated block (from [`BEGIN`] to [`END`]).
#[must_use]
pub fn render(m: &Measures) -> String {
    let mut s = format!("{BEGIN}\n\n");
    let in_cycles: usize = m.recursion.iter().map(|c| c.functions.len()).sum();
    let exported = m.macros.iter().filter(|d| d.exported).count();
    let unqualified = m.macros.iter().filter(|d| !d.unqualified.is_empty()).count();
    let d = &m.div;
    s.push_str("| # | Measure (product code) | Count |\n|---|---|---|\n");
    let _ = writeln!(
        s,
        "| G1 | functions on a recursion cycle found by the call-graph scan (cycles) | {in_cycles} ({}) |",
        m.recursion.len()
    );
    let _ = writeln!(
        s,
        "| G3 | divisors that are not literals: `NonZero` type / guard / `// DIV:` proof / named constant (exempt: rustc) / **missing** | {} / {} / {} / {} / **{}** |",
        d.nonzero, d.guarded, d.proven, d.constant, d.missing
    );
    let _ = writeln!(s, "| G4 | integer divisions and remainders | {} |", d.integer());
    let _ = writeln!(
        s,
        "| G5 | shifts by a non-literal amount: run-time (each with a `// SHIFT:` proof) / named constant (exempt: rustc) | {} / {} |",
        m.shifts.0, m.shifts.1
    );
    let _ = writeln!(
        s,
        "| G11 | `macro_rules!` definitions (exported) | {} ({exported}) |",
        m.macros.len()
    );
    let _ = writeln!(
        s,
        "| G12 | macros whose transcribers use a name without a path | {unqualified} |"
    );
    s.push_str("\n**G1: recursion cycles** (direct recursion is a cycle of one function).\n\n");
    if m.recursion.is_empty() {
        s.push_str("None found.\n");
    } else {
        s.push_str("| Crate | Functions | Files |\n|---|---|---|\n");
        for c in &m.recursion {
            let _ = writeln!(
                s,
                "| {} | {} | {} |",
                c.krate,
                c.functions
                    .iter()
                    .map(|f| format!("`{f}`"))
                    .collect::<Vec<_>>()
                    .join(" ↔ "),
                c.files
                    .iter()
                    .map(|f| format!("`{f}`"))
                    .collect::<Vec<_>>()
                    .join(", ")
            );
        }
    }
    s.push_str("\n**G11/G12: `macro_rules!` definitions** (*exported*: `#[macro_export]`).\n\n");
    s.push_str("| Crate | Macro | File | Names without a path |\n|---|---|---|---|\n");
    for d in &m.macros {
        let _ = writeln!(
            s,
            "| {} | `{}`{} | `{}` | {} |",
            d.krate,
            d.name,
            if d.exported { " *exported*" } else { "" },
            d.file,
            if d.unqualified.is_empty() {
                "—".to_owned()
            } else {
                d.unqualified
                    .iter()
                    .map(|n| format!("`{n}`"))
                    .collect::<Vec<_>>()
                    .join(", ")
            }
        );
    }
    s.push('\n');
    s.push_str(END);
    s
}

// ---- G1: recursion -------------------------------------------------------------------------

/// A recursion cycle (a strongly connected component of the call graph with a cycle).
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub struct Cycle {
    /// The crate.
    pub krate: String,
    /// The functions on it (`module::f` or `Type::f`), sorted.
    pub functions: Vec<String>,
    /// Their files (relative to the crate), sorted.
    pub files: Vec<String>,
}

/// A function of the call graph.
#[derive(Debug, Default)]
struct FnNode {
    file: String,
    /// The module the function is defined in (where unqualified calls resolve first).
    module: Vec<String>,
    calls: Vec<Call>,
}

/// A call as written.
#[derive(Clone, Debug)]
enum Call {
    /// `f(..)` or `a::b::f(..)`: the path segments.
    Path(Vec<String>),
    /// `self.f(..)` / `Self::f(..)` inside an impl of `Type`, or `Type::f(..)`.
    Method(String, String),
}

/// Collects the functions and their calls of one file.
struct Calls<'a> {
    file: &'a SourceFile,
    /// The module path of the file plus inline modules.
    module: Vec<String>,
    /// The `Self` type (impl) or trait name, innermost last, with the implemented trait (`None`
    /// for an inherent impl or a trait definition).
    self_ty: Vec<(String, Option<String>)>,
    /// The function being visited (its key), innermost last.
    current: Vec<String>,
    fns: &'a mut BTreeMap<String, FnNode>,
}

impl Calls<'_> {
    fn enter(&mut self, key: String) {
        self.fns.entry(key.clone()).or_insert_with(|| FnNode {
            file: self.file.rel.clone(),
            module: self.module.clone(),
            calls: Vec::new(),
        });
        self.current.push(key);
    }

    fn add(&mut self, call: Call) {
        if let Some(cur) = self.current.last()
            && let Some(node) = self.fns.get_mut(cur)
        {
            node.calls.push(call);
        }
    }
}

/// The last segment of a type's path (`Engine` for `crate::Engine<'a>`).
fn type_name(ty: &syn::Type) -> Option<String> {
    match ty {
        syn::Type::Path(p) => p.path.segments.last().map(|s| s.ident.to_string()),
        syn::Type::Reference(r) => type_name(&r.elem),
        _ => None,
    }
}

impl<'ast> Visit<'ast> for Calls<'_> {
    fn visit_item_mod(&mut self, m: &'ast syn::ItemMod) {
        if is_test_cfg(&m.attrs) {
            return;
        }
        if m.content.is_some() {
            self.module.push(m.ident.to_string());
            visit::visit_item_mod(self, m);
            self.module.pop();
        }
    }

    fn visit_item_fn(&mut self, f: &'ast syn::ItemFn) {
        if is_test_cfg(&f.attrs) {
            return;
        }
        let mut path = self.module.clone();
        path.push(f.sig.ident.to_string());
        self.enter(path.join("::"));
        visit::visit_item_fn(self, f);
        self.current.pop();
    }

    fn visit_item_impl(&mut self, i: &'ast syn::ItemImpl) {
        if is_test_cfg(&i.attrs) {
            return;
        }
        let Some(name) = type_name(&i.self_ty) else { return };
        let tr = i
            .trait_
            .as_ref()
            .and_then(|(_, p, _)| p.segments.last())
            .map(|s| s.ident.to_string());
        self.self_ty.push((name, tr));
        visit::visit_item_impl(self, i);
        self.self_ty.pop();
    }

    fn visit_item_trait(&mut self, t: &'ast syn::ItemTrait) {
        if is_test_cfg(&t.attrs) {
            return;
        }
        self.self_ty.push((t.ident.to_string(), None));
        visit::visit_item_trait(self, t);
        self.self_ty.pop();
    }

    fn visit_impl_item_fn(&mut self, f: &'ast syn::ImplItemFn) {
        if is_test_cfg(&f.attrs) {
            return;
        }
        // A trait impl's method is `Type as Trait::f`: a `self.f(..)` call in it resolves to an
        // inherent `Type::f` first, as in Rust.
        let (ty, tr) = self.self_ty.last().cloned().unwrap_or_default();
        let key = match tr {
            Some(tr) => format!("{ty} as {tr}::{}", f.sig.ident),
            None => format!("{ty}::{}", f.sig.ident),
        };
        self.enter(key);
        visit::visit_impl_item_fn(self, f);
        self.current.pop();
    }

    fn visit_trait_item_fn(&mut self, f: &'ast syn::TraitItemFn) {
        if is_test_cfg(&f.attrs) || f.default.is_none() {
            return;
        }
        let (ty, _) = self.self_ty.last().cloned().unwrap_or_default();
        self.enter(format!("{ty}::{}", f.sig.ident));
        visit::visit_trait_item_fn(self, f);
        self.current.pop();
    }

    fn visit_expr_call(&mut self, c: &'ast syn::ExprCall) {
        if let syn::Expr::Path(p) = &*c.func {
            let segs: Vec<String> = p.path.segments.iter().map(|s| s.ident.to_string()).collect();
            match segs.as_slice() {
                [ty, f] if ty == "Self" => {
                    if let Some((t, _)) = self.self_ty.last().cloned() {
                        self.add(Call::Method(t, f.clone()));
                    }
                }
                [.., ty, f] if ty.chars().next().is_some_and(char::is_uppercase) => {
                    self.add(Call::Method(ty.clone(), f.clone()));
                }
                _ => self.add(Call::Path(segs)),
            }
        }
        visit::visit_expr_call(self, c);
    }

    fn visit_expr_method_call(&mut self, m: &'ast syn::ExprMethodCall) {
        if let syn::Expr::Path(p) = &*m.receiver
            && p.path.is_ident("self")
            && let Some((t, _)) = self.self_ty.last().cloned()
        {
            self.add(Call::Method(t, m.method.to_string()));
        }
        visit::visit_expr_method_call(self, m);
    }
}

/// The module path of a file (`crates/x/src/a/b.rs` → `a::b`; `lib.rs`/`mod.rs` → the dir).
fn module_of(rel: &str) -> Vec<String> {
    let path = rel.split_once("/src/").map_or(rel, |(_, p)| p);
    let path = path.strip_suffix(".rs").unwrap_or(path);
    let mut segs: Vec<String> = path.split('/').map(str::to_owned).collect();
    if matches!(segs.last().map(String::as_str), Some("lib" | "mod" | "main")) {
        segs.pop();
    }
    segs
}

/// The recursion cycles of the product code, per crate.
#[must_use]
pub fn recursion(files: &[SourceFile]) -> Vec<Cycle> {
    let crates: BTreeSet<&str> = files.iter().map(|f| f.krate.as_str()).collect();
    let mut out = Vec::new();
    for krate in crates {
        let mut fns = BTreeMap::new();
        for file in files.iter().filter(|f| f.krate == krate) {
            let Ok(ast) = syn::parse_file(&file.src) else {
                continue;
            };
            let mut v = Calls {
                file,
                module: module_of(&file.rel),
                self_ty: Vec::new(),
                current: Vec::new(),
                fns: &mut fns,
            };
            v.visit_file(&ast);
        }
        for scc in cycles(&fns) {
            let files: BTreeSet<String> = scc
                .iter()
                .filter_map(|k| fns.get(k))
                .map(|n| {
                    n.file
                        .strip_prefix(&format!("crates/{krate}/"))
                        .unwrap_or(&n.file)
                        .to_owned()
                })
                .collect();
            out.push(Cycle {
                krate: krate.to_owned(),
                functions: scc,
                files: files.into_iter().collect(),
            });
        }
    }
    out.sort();
    out
}

/// Resolves a call to function keys of `fns`.
fn resolve(fns: &BTreeMap<String, FnNode>, from: &str, call: &Call) -> Option<String> {
    match call {
        Call::Method(ty, f) => {
            // The inherent method, else the one trait impl of `Type` with that name.
            let key = format!("{ty}::{f}");
            if fns.contains_key(&key) {
                return Some(key);
            }
            // Never the calling trait method itself: without an inherent method, `self.f(..)` in
            // `Type as Trait::f` names another trait's `f` (possibly of another crate).
            let (prefix, suffix) = (format!("{ty} as "), format!("::{f}"));
            let mut hits = fns
                .keys()
                .filter(|k| k.starts_with(&prefix) && k.ends_with(&suffix) && k.as_str() != from);
            let first = hits.next()?;
            hits.next().is_none().then(|| first.clone())
        }
        Call::Path(segs) => {
            let segs: Vec<&str> = segs
                .iter()
                .map(String::as_str)
                .filter(|s| !matches!(*s, "crate" | "self" | "super"))
                .collect();
            let (name, prefix) = segs.split_last()?;
            // Same module first, then a unique match of the path's tail.
            if prefix.is_empty() {
                let mut local: Vec<&str> = fns.get(from)?.module.iter().map(String::as_str).collect();
                local.push(name);
                let key = local.join("::");
                if fns.contains_key(&key) {
                    return Some(key);
                }
            }
            let tail = segs.join("::");
            let mut hits = fns
                .keys()
                .filter(|k| *k == &tail || k.ends_with(&format!("::{tail}")))
                .filter(|k| {
                    !k.split("::")
                        .any(|s| s.chars().next().is_some_and(char::is_uppercase))
                });
            let first = hits.next()?;
            hits.next().is_none().then(|| first.clone())
        }
    }
}

/// Tarjan's strongly-connected-components search over a call graph.
struct Tarjan<'e> {
    edges: &'e [BTreeSet<usize>],
    index: Vec<Option<usize>>,
    low: Vec<usize>,
    on_stack: Vec<bool>,
    stack: Vec<usize>,
    next: usize,
    out: Vec<Vec<usize>>,
}

impl Tarjan<'_> {
    fn visit(&mut self, v: usize) {
        self.index[v] = Some(self.next);
        self.low[v] = self.next;
        self.next += 1;
        self.stack.push(v);
        self.on_stack[v] = true;
        for &w in &self.edges[v] {
            match self.index[w] {
                None => {
                    self.visit(w);
                    self.low[v] = self.low[v].min(self.low[w]);
                }
                Some(iw) if self.on_stack[w] => self.low[v] = self.low[v].min(iw),
                Some(_) => {}
            }
        }
        if Some(self.low[v]) == self.index[v] {
            let mut scc = Vec::new();
            while let Some(w) = self.stack.pop() {
                self.on_stack[w] = false;
                scc.push(w);
                if w == v {
                    break;
                }
            }
            if scc.len() > 1 || self.edges[v].contains(&v) {
                self.out.push(scc);
            }
        }
    }
}

/// The strongly connected components with a cycle (Tarjan), each sorted.
fn cycles(fns: &BTreeMap<String, FnNode>) -> Vec<Vec<String>> {
    let keys: Vec<&String> = fns.keys().collect();
    let index_of: BTreeMap<&String, usize> = keys.iter().enumerate().map(|(i, k)| (*k, i)).collect();
    let edges: Vec<BTreeSet<usize>> = keys
        .iter()
        .map(|k| {
            fns[*k]
                .calls
                .iter()
                .filter_map(|c| resolve(fns, k, c))
                .filter_map(|t| index_of.get(&t).copied())
                .collect()
        })
        .collect();
    let n = keys.len();
    let mut t = Tarjan {
        edges: &edges,
        index: vec![None; n],
        low: vec![0; n],
        on_stack: vec![false; n],
        stack: Vec::new(),
        next: 0,
        out: Vec::new(),
    };
    for v in 0..n {
        if t.index[v].is_none() {
            t.visit(v);
        }
    }
    let mut out: Vec<Vec<String>> = t
        .out
        .into_iter()
        .map(|scc| {
            let mut names: Vec<String> = scc.into_iter().map(|i| keys[i].clone()).collect();
            names.sort();
            names
        })
        .collect();
    out.sort();
    out
}

