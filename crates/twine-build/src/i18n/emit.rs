//! Writes a [`Catalog`] as Rust: the `Key` and `Lang` enums, their `twine_extra::i18n` trait
//! impls and one static message table per language. Deterministic: the output depends only on
//! the translations and options (file names, not paths, are named in the header).

use std::fmt::Write as _;
use std::path::Path;

use super::model::{Body, Seg, Sel};
use super::{Catalog, Dir, KeyOut};

/// A Markdown code span containing `text` (newlines shown as `⏎`), so translations never turn
/// into links or emphasis in rustdoc.
fn code_span(text: &str) -> String {
    let text = text.replace('\n', "⏎");
    let mut longest = 0;
    let mut run = 0;
    for c in text.chars() {
        run = if c == '`' { run + 1 } else { 0 };
        longest = longest.max(run);
    }
    let fence = "`".repeat(longest + 1);
    let pad = if text.starts_with('`') || text.ends_with('`') || text.is_empty() {
        " "
    } else {
        ""
    };
    format!("{fence}{pad}{text}{pad}{fence}")
}

/// `#[doc = "…"]` with `text` escaped as a Rust string literal.
fn doc(o: &mut String, indent: &str, text: &str) {
    let _ = writeln!(o, "{indent}#[doc = {text:?}]");
}

/// Groups `items` by `value(item)` into `A | B => value` match arms (in first-seen order).
fn arms<T>(
    o: &mut String,
    indent: &str,
    items: &[T],
    pat: impl Fn(&T) -> String,
    value: impl Fn(&T) -> String,
) {
    let mut groups: Vec<(String, Vec<String>)> = Vec::new();
    for it in items {
        let v = value(it);
        match groups.iter_mut().find(|(gv, _)| *gv == v) {
            Some((_, pats)) => pats.push(pat(it)),
            None => groups.push((v, vec![pat(it)])),
        }
    }
    for (v, pats) in groups {
        let _ = writeln!(o, "{indent}{} => {v},", pats.join(" | "));
    }
}

fn segments(segs: &[Seg], key: &KeyOut) -> String {
    let parts: Vec<String> = segs
        .iter()
        .map(|s| match s {
            Seg::Text(t) => format!("rt::Segment::Text({t:?})"),
            Seg::Arg(a) => format!("rt::Segment::Arg({})", arg_index(key, a)),
        })
        .collect();
    format!("&[{}]", parts.join(", "))
}

fn arg_index(key: &KeyOut, name: &str) -> usize {
    // The builder checked that every argument is one of the key's.
    key.args.iter().position(|a| a == name).unwrap_or(0)
}

fn message(body: &Body, key: &KeyOut) -> String {
    match body {
        Body::Pattern(segs) => match segs.as_slice() {
            [] => "rt::Message::Text(\"\")".to_string(),
            [Seg::Text(t)] => format!("rt::Message::Text({t:?})"),
            _ => format!("rt::Message::Format({})", segments(segs, key)),
        },
        Body::Plural {
            selector,
            variants,
            other,
        } => {
            let mut vs: Vec<&(Sel, Vec<Seg>)> = variants.iter().collect();
            // Exact values first (the runtime checks them before the categories).
            vs.sort_by_key(|(sel, _)| *sel);
            let vs: Vec<String> = vs
                .iter()
                .map(|(sel, segs)| {
                    let sel = match sel {
                        Sel::Exact(n) => format!("rt::Selector::Exact({n})"),
                        Sel::Cat(c) => format!("rt::Selector::Category(rt::PluralCategory::{})", c.variant()),
                    };
                    format!(
                        "rt::Variant {{ selector: {sel}, segments: {} }}",
                        segments(segs, key)
                    )
                })
                .collect();
            format!(
                "rt::Message::Plural(&rt::Plural {{ arg: {}, variants: &[{}], other: {} }})",
                arg_index(key, selector),
                vs.join(", "),
                segments(other, key)
            )
        }
        // Resolved by the builder.
        Body::Forms { .. } => "rt::Message::Text(\"\")".to_string(),
    }
}

/// The Rust source of `c`.
#[allow(clippy::too_many_lines)]
pub(super) fn rust(c: &Catalog) -> String {
    let rt = &c.runtime;
    let mut o = String::new();
    let files: Vec<String> = c
        .langs
        .iter()
        .map(|l| {
            Path::new(&l.file)
                .file_name()
                .map_or_else(|| l.file.clone(), |f| f.to_string_lossy().into_owned())
        })
        .collect();
    let _ = writeln!(
        o,
        "// @generated by twine-build {} from {} — do not edit: change the translations and \
         regenerate.",
        env!("CARGO_PKG_VERSION"),
        files.join(", ")
    );
    let _ = writeln!(
        o,
        "// {} language(s), {} key(s); runtime: `{rt}`.\n",
        c.langs.len(),
        c.keys.len()
    );

    // ---- Key ----
    let default = &c.langs[c.default];
    doc(
        &mut o,
        "",
        "The message keys of the translation catalog: one variant per message, named after its identifier (generated by `twine-build`).",
    );
    doc(&mut o, "", "");
    doc(
        &mut o,
        "",
        "Show a message with `tr!(Key::Greeting)` or `tr!(Key::Items, count = n)`: the arguments are checked against [`Key::args`] at compile time.",
    );
    o.push_str("#[derive(Clone, Copy, PartialEq, Eq, Hash)]\n#[allow(dead_code)] // an application need not use every key\npub enum Key {\n");
    for (k, body) in c.keys.iter().zip(&c.messages[c.default]) {
        let args = if k.args.is_empty() {
            String::new()
        } else {
            format!(
                " ({})",
                k.args
                    .iter()
                    .map(|a| format!("`{a}`"))
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        };
        let text = format!(
            "`{}`{args}: {} ({}).",
            k.id,
            code_span(&super::preview(body)),
            default.code
        );
        doc(&mut o, "    ", &text);
        let _ = writeln!(o, "    {},", k.variant);
    }
    o.push_str("}\n\n#[allow(dead_code)]\nimpl Key {\n");
    doc(
        &mut o,
        "    ",
        "Every key, in declaration order (sorted by identifier).",
    );
    let _ = writeln!(
        o,
        "    pub const ALL: [Key; {}] = [{}];\n",
        c.keys.len(),
        c.keys
            .iter()
            .map(|k| format!("Key::{}", k.variant))
            .collect::<Vec<_>>()
            .join(", ")
    );
    doc(&mut o, "    ", "The key's identifier in the translation files.");
    o.push_str("    #[must_use]\n    pub const fn id(self) -> &'static str {\n        match self {\n");
    for k in &c.keys {
        let _ = writeln!(o, "            Key::{} => {:?},", k.variant, k.id);
    }
    o.push_str("        }\n    }\n\n");
    doc(
        &mut o,
        "    ",
        "The names of the key's arguments (positional ones are `\"0\"`, `\"1\"`, …), in canonical order: what `tr!` checks its arguments against at compile time.",
    );
    o.push_str(
        "    #[must_use]\n    pub const fn args(self) -> &'static [&'static str] {\n        match self {\n",
    );
    arms(
        &mut o,
        "            ",
        &c.keys,
        |k| format!("Key::{}", k.variant),
        |k| {
            format!(
                "&[{}]",
                k.args
                    .iter()
                    .map(|a| format!("{a:?}"))
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        },
    );
    o.push_str("        }\n    }\n}\n\n");
    o.push_str(
        "impl ::core::fmt::Debug for Key {\n    fn fmt(&self, f: &mut ::core::fmt::Formatter<'_>) -> ::core::fmt::Result {\n        f.write_str(self.id())\n    }\n}\n\n",
    );
    let _ = writeln!(
        o,
        "impl {rt}::MessageKey for Key {{\n    type Lang = Lang;\n\n    #[inline]\n    fn index(self) -> usize {{\n        self as usize\n    }}\n\n    #[inline]\n    fn id(self) -> &'static str {{\n        Key::id(self)\n    }}\n}}\n"
    );

    // ---- Lang ----
    doc(
        &mut o,
        "",
        "The languages of the translation catalog (generated by `twine-build`).",
    );
    doc(&mut o, "", "");
    doc(
        &mut o,
        "",
        "Switch with `I18n::set_language`; every `tr!` text follows.",
    );
    o.push_str("#[derive(Clone, Copy, PartialEq, Eq, Hash)]\n#[allow(dead_code)] // switching to every language is up to the application\npub enum Lang {\n");
    for (i, l) in c.langs.iter().enumerate() {
        let dir = match l.dir {
            Dir::Ltr => "left to right",
            Dir::Rtl => "right to left",
        };
        let role = if i == c.default { "default language, " } else { "" };
        doc(
            &mut o,
            "    ",
            &format!("`{}` ({role}{dir}, plural rules `{}`).", l.code, l.rules.name),
        );
        let _ = writeln!(o, "    {},", l.variant);
    }
    o.push_str("}\n\n#[allow(dead_code)]\nimpl Lang {\n");
    doc(&mut o, "    ", "Every language, in declaration order.");
    let _ = writeln!(
        o,
        "    pub const ALL: [Lang; {}] = [{}];\n",
        c.langs.len(),
        c.langs
            .iter()
            .map(|l| format!("Lang::{}", l.variant))
            .collect::<Vec<_>>()
            .join(", ")
    );
    doc(
        &mut o,
        "    ",
        "The default language: the others fall back to it for missing texts.",
    );
    let _ = writeln!(o, "    pub const DEFAULT: Lang = Lang::{};\n", default.variant);
    doc(
        &mut o,
        "    ",
        "The language code (the stem of its translation file).",
    );
    o.push_str("    #[must_use]\n    pub const fn code(self) -> &'static str {\n        match self {\n");
    for l in &c.langs {
        let _ = writeln!(o, "            Lang::{} => {:?},", l.variant, l.code);
    }
    o.push_str("        }\n    }\n\n");
    doc(
        &mut o,
        "    ",
        "The language with code `code`, if the catalog has it.",
    );
    o.push_str("    #[must_use]\n    pub fn from_code(code: &str) -> Option<Lang> {\n        match code {\n");
    for l in &c.langs {
        let _ = writeln!(o, "            {:?} => Some(Lang::{}),", l.code, l.variant);
    }
    o.push_str("            _ => None,\n        }\n    }\n\n");
    doc(&mut o, "    ", "The language's base text direction.");
    let _ = writeln!(
        o,
        "    #[must_use]\n    pub const fn base_dir(self) -> {rt}::BaseDir {{\n        match self {{"
    );
    arms(
        &mut o,
        "            ",
        &c.langs,
        |l| format!("Lang::{}", l.variant),
        |l| match l.dir {
            Dir::Ltr => format!("{rt}::BaseDir::Ltr"),
            Dir::Rtl => format!("{rt}::BaseDir::Rtl"),
        },
    );
    o.push_str("        }\n    }\n\n");
    doc(
        &mut o,
        "    ",
        "The language's font, if the catalog names one (`Translations::font`).",
    );
    let _ = writeln!(
        o,
        "    #[must_use]\n    pub fn font(self) -> Option<&'static {rt}::Font> {{\n        match self {{"
    );
    arms(
        &mut o,
        "            ",
        &c.langs,
        |l| format!("Lang::{}", l.variant),
        |l| {
            l.font
                .as_ref()
                .map_or_else(|| "None".to_string(), |f| format!("Some(&{f})"))
        },
    );
    o.push_str("        }\n    }\n}\n\n");
    o.push_str(
        "impl ::core::fmt::Debug for Lang {\n    fn fmt(&self, f: &mut ::core::fmt::Formatter<'_>) -> ::core::fmt::Result {\n        f.write_str(self.code())\n    }\n}\n\n",
    );
    let _ = writeln!(o, "impl {rt}::Language for Lang {{");
    let _ = writeln!(o, "    const DEFAULT: Self = Lang::{};", default.variant);
    o.push_str("    const ALL: &'static [Self] = &Lang::ALL;\n");
    let _ = writeln!(o, "    const NUMBER_FORMATS: &'static [{rt}::NumberFormat] = &[");
    for l in &c.langs {
        let n = &l.numbers;
        let _ = writeln!(
            o,
            "        // {}\n        {rt}::NumberFormat {{ decimal: {:?}, group: {:?}, primary_group: {}, secondary_group: {}, min_grouping: {}, minus: {:?}, percent_prefix: {:?}, percent_suffix: {:?}, zero: {:?} }},",
            l.code,
            n.decimal,
            n.group,
            n.primary_group,
            n.secondary_group,
            n.min_grouping,
            n.minus,
            n.percent_prefix,
            n.percent_suffix,
            n.zero
        );
    }
    o.push_str("    ];\n\n");
    o.push_str("    #[inline]\n    fn index(self) -> usize {\n        self as usize\n    }\n\n");
    o.push_str("    fn code(self) -> &'static str {\n        Lang::code(self)\n    }\n\n");
    let _ = writeln!(
        o,
        "    fn base_dir(self) -> {rt}::BaseDir {{\n        Lang::base_dir(self)\n    }}\n"
    );
    let _ = writeln!(
        o,
        "    fn font(self) -> Option<&'static {rt}::Font> {{\n        Lang::font(self)\n    }}\n"
    );
    let _ = writeln!(
        o,
        "    fn plural_rule(self) -> {rt}::PluralRule {{\n        match self {{"
    );
    arms(
        &mut o,
        "            ",
        &c.langs,
        |l| format!("Lang::{}", l.variant),
        |l| format!("{rt}::plural::{}", l.rules.name),
    );
    o.push_str("        }\n    }\n\n");
    let _ = writeln!(
        o,
        "    fn messages(self) -> &'static [{rt}::Message] {{\n        match self {{"
    );
    for l in &c.langs {
        let _ = writeln!(
            o,
            "            Lang::{} => &__messages::{},",
            l.variant,
            static_name(&l.code)
        );
    }
    o.push_str("        }\n    }\n}\n\n");

    // ---- Message tables ----
    o.push_str("/// The message tables, one per language, indexed by `Key`.\nmod __messages {\n");
    let _ = writeln!(o, "    use {rt} as rt;\n");
    for (l, row) in c.langs.iter().zip(&c.messages) {
        let name = static_name(&l.code);
        let _ = writeln!(o, "    /// `{}`.", l.code);
        let _ = writeln!(
            o,
            "    pub(super) static {name}: [rt::Message; {}] = [",
            c.keys.len()
        );
        for (k, body) in c.keys.iter().zip(row) {
            let _ = writeln!(o, "        // {}", k.id);
            let _ = writeln!(o, "        {},", message(body, k));
        }
        o.push_str("    ];\n");
    }
    o.push_str("}\n");
    o
}

/// The static holding the messages of language `code` (`"pt-BR"` → `PT_BR`).
fn static_name(code: &str) -> String {
    code.chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn code_spans_escape_backticks() {
        assert_eq!(code_span("a"), "`a`");
        assert_eq!(code_span("a`b"), "``a`b``");
        assert_eq!(code_span("`x`"), "`` `x` ``");
        assert_eq!(code_span("a\nb"), "`a⏎b`");
    }
}
