//! Rust source of a converted image.

use std::fmt::Write as _;

use twine_core::ColorFormat;
use twine_image::ImageHeader;

use super::Compression;

/// The Rust variant name of `f` (`ColorFormat::<name>`).
pub(crate) fn variant(f: ColorFormat) -> &'static str {
    match f {
        ColorFormat::L8 => "L8",
        ColorFormat::A1 => "A1",
        ColorFormat::A2 => "A2",
        ColorFormat::A4 => "A4",
        ColorFormat::A8 => "A8",
        ColorFormat::I1 => "I1",
        ColorFormat::I2 => "I2",
        ColorFormat::I4 => "I4",
        ColorFormat::I8 => "I8",
        ColorFormat::Rgb565 => "Rgb565",
        ColorFormat::Rgb565Swapped => "Rgb565Swapped",
        ColorFormat::Rgb565A8 => "Rgb565A8",
        ColorFormat::Rgb888 => "Rgb888",
        ColorFormat::Argb8888 => "Argb8888",
        ColorFormat::Xrgb8888 => "Xrgb8888",
        ColorFormat::Argb8888Premultiplied => "Argb8888Premultiplied",
    }
}

/// Where the generated source finds the (stored) pixel data.
pub(crate) enum DataRef<'a> {
    /// `include_bytes!` of a sidecar file next to the source.
    Sidecar(&'a str),
    /// A byte-string literal in the source (the `include_image!` macro).
    Inline(&'a [u8]),
}

/// Everything the source file mentions.
pub(crate) struct Emit<'a> {
    /// Static name.
    pub(crate) name: &'a str,
    /// Visibility of the static (`pub`, `pub(crate)`, empty).
    pub(crate) visibility: &'a str,
    /// Path of the crate that defines `Image` (e.g. `twine_image`).
    pub(crate) crate_path: &'a str,
    /// The command line that produced the file.
    pub(crate) command: &'a str,
    /// SHA-256 of the input file.
    pub(crate) input_sha256: &'a str,
    /// Header of the pixel data (with `COMPRESSED` set when compressed).
    pub(crate) header: ImageHeader,
    /// Compression.
    pub(crate) compress: Compression,
    /// The stored data.
    pub(crate) data: DataRef<'a>,
    /// Bytes stored (compressed or not).
    pub(crate) stored_len: usize,
    /// Uncompressed size.
    pub(crate) data_len: usize,
}

/// The machine-readable summary line (also read by `twine image --info`).
pub(crate) fn summary(e: &Emit<'_>) -> String {
    format!(
        "// twine-image: format={} w={} h={} stride={} flags={:#04x} compression={} stored={} size={}",
        e.header.format.name(),
        e.header.w,
        e.header.h,
        e.header.stride,
        e.header.flags.bits(),
        e.compress.name(),
        e.stored_len,
        e.data_len
    )
}

/// Renders the `.rs` file.
pub(crate) fn render(e: &Emit<'_>) -> String {
    let c = e.crate_path;
    let mut s = String::new();
    let _ = writeln!(s, "// Generated by `twine image`; do not edit.");
    let _ = writeln!(s, "// Command: {}", e.command);
    let _ = writeln!(s, "// Input SHA-256: {}", e.input_sha256);
    let _ = writeln!(s, "{}", summary(e));
    let _ = writeln!(s);
    let header = format!(
        "{c}::ImageHeader {{\n        format: {c}::ColorFormat::{},\n        w: {},\n        h: {},\n        stride: {},\n        flags: {c}::ImageFlags::from_bits_retain({:#04x}),\n    }}",
        variant(e.header.format),
        e.header.w,
        e.header.h,
        e.header.stride,
        e.header.flags.bits()
    );
    let _ = writeln!(
        s,
        "/// `{}` ({}×{} `{}`).",
        e.name,
        e.header.w,
        e.header.h,
        e.header.format.name()
    );
    let data = match e.data {
        DataRef::Sidecar(bin_name) => format!("include_bytes!(\"{bin_name}\")"),
        DataRef::Inline(bytes) => {
            let mut lit = String::with_capacity(bytes.len() * 4 + 3);
            lit.push_str("b\"");
            for b in bytes {
                let _ = write!(lit, "\\x{b:02x}");
            }
            lit.push('"');
            lit
        }
    };
    let vis = if e.visibility.is_empty() {
        String::new()
    } else {
        format!("{} ", e.visibility)
    };
    match e.compress {
        Compression::None => {
            let _ = writeln!(
                s,
                "{vis}static {}: {c}::Image = {c}::Image::new_static(\n    {header},\n    {data},\n);",
                e.name
            );
        }
        Compression::Rle | Compression::Lz4 => {
            let method = if e.compress == Compression::Rle {
                "Rle"
            } else {
                "Lz4"
            };
            let _ = writeln!(
                s,
                "{vis}static {}: {c}::Image = {c}::Image {{\n    header: {header},\n    data: {c}::ImageData::Compressed {{\n        method: {c}::Compression::{method},\n        data: {data},\n        decompressed_size: {},\n    }},\n}};",
                e.name, e.data_len
            );
        }
    }
    s
}
