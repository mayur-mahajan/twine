//! Rust source output of the font generator.

use std::fmt::Write as _;

use twine_text::encode::{FontData, KernData};
use twine_text::{BitmapFormat, CmapKind, GammaRamp, Subpx};

use super::{Gamma, Hinting};

fn bytes_array(out: &mut String, name: &str, data: &[u8]) {
    let _ = writeln!(out, "#[rustfmt::skip]\nstatic {name}: [u8; {}] = [", data.len());
    for chunk in data.chunks(16) {
        out.push_str("   ");
        for b in chunk {
            let _ = write!(out, " 0x{b:02x},");
        }
        out.push('\n');
    }
    out.push_str("];\n\n");
}

fn u16_array(out: &mut String, name: &str, data: &[u16]) {
    let _ = writeln!(out, "#[rustfmt::skip]\nstatic {name}: [u16; {}] = [", data.len());
    for chunk in data.chunks(12) {
        out.push_str("   ");
        for v in chunk {
            let _ = write!(out, " 0x{v:04x},");
        }
        out.push('\n');
    }
    out.push_str("];\n\n");
}

fn describe_char(c: char) -> String {
    if c == '\0' {
        "reserved".to_string()
    } else if c.is_control() || (0xE000..=0xF8FF).contains(&u32::from(c)) {
        format!("U+{:04X}", u32::from(c))
    } else {
        format!("U+{:04X} {c:?}", u32::from(c))
    }
}

/// Everything the generated source mentions.
pub(crate) struct FontEmit<'a> {
    /// Static name.
    pub(crate) name: &'a str,
    /// Visibility of the font static (`pub`, `pub(crate)`, empty).
    pub(crate) visibility: &'a str,
    /// Path of the text crate in the generated code (`twine::text`, `twine_text`).
    pub(crate) crate_path: &'a str,
    /// The equivalent `twine font` command line.
    pub(crate) command: &'a str,
    /// Pixel size.
    pub(crate) size: u16,
    /// Hinting mode.
    pub(crate) hinting: Hinting,
    /// The rasterizer (and hinter) versions.
    pub(crate) rasterizer: &'static str,
    /// Text gamma strengths (the tables are in `data`).
    pub(crate) gamma: Gamma,
    /// Source font file name and SHA-256.
    pub(crate) source: (String, String),
    /// Symbol font file names and SHA-256s.
    pub(crate) symbols: &'a [(String, String)],
    /// The font.
    pub(crate) data: &'a FontData,
    /// Code point of every glyph id.
    pub(crate) code_points: &'a [char],
}

/// Renders the Rust source of a generated font; returns it with the number of static data
/// bytes it contains.
pub(crate) fn render_rust(e: &FontEmit<'_>) -> (String, usize) {
    let n = e.name;
    let c = e.crate_path;
    let d = e.data;
    let code_points = e.code_points;
    let mut out = String::new();
    let mut flash = 0usize;
    let _ = writeln!(
        out,
        "// Generated by twine-build {}: {}",
        env!("CARGO_PKG_VERSION"),
        e.command
    );
    let _ = writeln!(out, "// Source: {} SHA-256 {}", e.source.0, e.source.1);
    for (f, h) in e.symbols {
        let _ = writeln!(out, "// Symbols: {f} SHA-256 {h}");
    }
    let _ = writeln!(out, "// Hinting: {} ({}).", e.hinting, e.rasterizer);
    let _ = writeln!(
        out,
        "// Text gamma: {} dark on light, {} light on dark.",
        gamma_str(e.gamma.dark_on_light()),
        gamma_str(e.gamma.light_on_dark())
    );
    let kern_pairs = match &d.kern {
        KernData::None => 0,
        KernData::Pairs { ids, .. } => ids.len(),
    };
    let fmt = match d.format {
        BitmapFormat::Plain => "plain",
        BitmapFormat::Compressed => "compressed",
        BitmapFormat::CompressedNoPrefilter => "compressed without prefilter",
    };
    let _ = writeln!(
        out,
        "// {} glyphs, line height {} px, base line {} px, {} bpp, {fmt} bitmaps, {kern_pairs} kerning pairs.",
        code_points.len() - 1,
        d.line_height,
        d.base_line,
        d.bpp.bits()
    );
    out.push_str("// Do not edit: regenerate with the command above.\n\n");

    bytes_array(&mut out, &format!("{n}_BITMAP"), &d.bitmap);
    flash += d.bitmap.len();

    let _ = writeln!(
        out,
        "#[rustfmt::skip]\nstatic {n}_GLYPHS: [{c}::GlyphDsc; {}] = [",
        d.glyphs.len()
    );
    for (g, ch) in d.glyphs.iter().zip(code_points) {
        let _ = writeln!(
            out,
            "    {c}::GlyphDsc {{ bitmap_index: {}, adv_w: {}, box_w: {}, box_h: {}, ofs_x: {}, ofs_y: {} }}, // {}",
            g.bitmap_index,
            g.adv_w,
            g.box_w,
            g.box_h,
            g.ofs_x,
            g.ofs_y,
            describe_char(*ch)
        );
    }
    out.push_str("];\n\n");
    flash += d.glyphs.len() * core::mem::size_of::<twine_text::GlyphDsc>();

    for (i, cm) in d.cmaps.iter().enumerate() {
        if !cm.unicode_list.is_empty() {
            u16_array(&mut out, &format!("{n}_UNICODE_LIST_{i}"), &cm.unicode_list);
            flash += cm.unicode_list.len() * 2;
        }
        if !cm.ofs_u8.is_empty() {
            bytes_array(&mut out, &format!("{n}_GLYPH_ID_OFS_{i}"), &cm.ofs_u8);
            flash += cm.ofs_u8.len();
        }
        if !cm.ofs_u16.is_empty() {
            u16_array(&mut out, &format!("{n}_GLYPH_ID_OFS_{i}"), &cm.ofs_u16);
            flash += cm.ofs_u16.len() * 2;
        }
    }
    let _ = writeln!(
        out,
        "#[rustfmt::skip]\nstatic {n}_CMAPS: [{c}::Cmap; {}] = [",
        d.cmaps.len()
    );
    for (i, cm) in d.cmaps.iter().enumerate() {
        let list = if cm.unicode_list.is_empty() {
            "&[]".to_string()
        } else {
            format!("&{n}_UNICODE_LIST_{i}")
        };
        let ofs = match cm.kind {
            CmapKind::Format0Full => format!("{c}::GlyphIdOfs::U8(&{n}_GLYPH_ID_OFS_{i})"),
            CmapKind::SparseFull => format!("{c}::GlyphIdOfs::U16(&{n}_GLYPH_ID_OFS_{i})"),
            _ => format!("{c}::GlyphIdOfs::None"),
        };
        let _ = writeln!(
            out,
            "    {c}::Cmap {{ range_start: 0x{:x}, range_length: {}, glyph_id_start: {}, unicode_list: {list}, glyph_id_ofs_list: {ofs}, kind: {c}::CmapKind::{:?} }},",
            cm.range_start, cm.range_length, cm.glyph_id_start, cm.kind
        );
    }
    out.push_str("];\n\n");
    flash += d.cmaps.len() * core::mem::size_of::<twine_text::Cmap>();

    let kern = match &d.kern {
        KernData::None => format!("{c}::Kern::None"),
        KernData::Pairs { ids, values } => {
            let u8_ids = d.kern.fits_u8();
            let (ty, w) = if u8_ids { ("u8", 1) } else { ("u16", 2) };
            let _ = writeln!(
                out,
                "#[rustfmt::skip]\nstatic {n}_KERN_PAIRS: [[{ty}; 2]; {}] = [",
                ids.len()
            );
            for chunk in ids.chunks(8) {
                out.push_str("   ");
                for p in chunk {
                    let _ = write!(out, " [{}, {}],", p[0], p[1]);
                }
                out.push('\n');
            }
            out.push_str("];\n\n");
            let _ = writeln!(
                out,
                "#[rustfmt::skip]\nstatic {n}_KERN_VALUES: [i8; {}] = [",
                values.len()
            );
            for chunk in values.chunks(16) {
                out.push_str("   ");
                for v in chunk {
                    let _ = write!(out, " {v},");
                }
                out.push('\n');
            }
            out.push_str("];\n\n");
            flash += ids.len() * 2 * w + values.len();
            format!(
                "{c}::Kern::Pairs {{\n        glyph_ids: {c}::KernPairIds::{}(&{n}_KERN_PAIRS),\n        values: &{n}_KERN_VALUES,\n    }}",
                if u8_ids { "U8" } else { "U16" }
            )
        }
    };

    // Gamma tables: the runtime crate's shared statics for the standard curves, written out
    // otherwise.
    let gamma = if e.gamma == Gamma::DEFAULT {
        format!("&{c}::gamma::DEFAULT")
    } else if e.gamma == Gamma::LINEAR {
        format!("&{c}::gamma::LINEAR")
    } else {
        let ramp = |r: &GammaRamp| {
            let t: Vec<String> = r.table4().iter().map(u8::to_string).collect();
            format!("{c}::GammaRamp::new([{}])", t.join(", "))
        };
        let _ = writeln!(
            out,
            "#[rustfmt::skip]\nstatic {n}_GAMMA: {c}::TextGamma = {c}::TextGamma {{\n    dark_on_light: {},\n    light_on_dark: {},\n}};\n",
            ramp(&d.gamma.dark_on_light),
            ramp(&d.gamma.light_on_dark)
        );
        flash += core::mem::size_of::<twine_text::TextGamma>();
        format!("&{n}_GAMMA")
    };

    let format = match d.format {
        BitmapFormat::Plain => "Plain",
        BitmapFormat::Compressed => "Compressed",
        BitmapFormat::CompressedNoPrefilter => "CompressedNoPrefilter",
    };
    let _ = writeln!(
        out,
        "static {n}_DATA: {c}::BitmapFont = {c}::BitmapFont {{\n    bpp: {c}::Bpp::{:?},\n    bitmap: &{n}_BITMAP,\n    glyphs: &{n}_GLYPHS,\n    cmaps: &{n}_CMAPS,\n    kern: {kern},\n    kern_scale: {},\n    format: {c}::BitmapFormat::{format},\n    gamma: {gamma},\n}};\n",
        d.bpp, d.kern_scale
    );
    flash += core::mem::size_of::<twine_text::BitmapFont>() + core::mem::size_of::<twine_text::Font>();

    let subpx = match d.subpx {
        Subpx::None => "None",
        Subpx::Hor => "Hor",
        Subpx::Ver => "Ver",
    };
    let vis = if e.visibility.is_empty() {
        String::new()
    } else {
        format!("{} ", e.visibility)
    };
    let _ = writeln!(
        out,
        "/// {} at {} px, {} bpp, {} glyphs (line height {} px).\n{vis}static {n}: {c}::Font = {c}::Font {{\n    line_height: {},\n    base_line: {},\n    underline_position: {},\n    underline_thickness: {},\n    provider: &{n}_DATA,\n    fallback: None,\n    subpx: {c}::Subpx::{subpx},\n}};",
        e.source.0,
        e.size,
        d.bpp.bits(),
        code_points.len() - 1,
        d.line_height,
        d.line_height,
        d.base_line,
        d.underline_position,
        d.underline_thickness
    );
    (out, flash)
}

/// `120` → `"1.2"`, `100` → `"1 (linear)"`.
fn gamma_str(centi: u16) -> String {
    if centi == 100 {
        return "1 (linear)".into();
    }
    let s = format!("{}.{:02}", centi / 100, centi % 100);
    s.trim_end_matches('0').trim_end_matches('.').to_string()
}
