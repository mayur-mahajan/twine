/// A font subset from Arabic text holds every presentation form and lam-alef ligature the
/// shaper can draw for its letters, and the partner of each mirrored bracket; implied
/// characters the font lacks are skipped without a warning.
#[test]
fn subset_holds_the_forms_shaping_and_mirroring_draw() {
    let text = "سلام لأحمد (Real)";
    let g = dejavu().chars_from(text).build().unwrap();
    assert!(g.warnings.is_empty(), "{:?}", g.warnings);
    // Every way the shaper writes these letters (alone, first, in the middle, last).
    let mut variants = vec![text.to_string()];
    for c in "سلامأحد".chars() {
        // Joined to `س` (in the text) on either side.
        for ctx in [format!("{c}"), format!("س{c}"), format!("{c}س"), format!("س{c}س")] {
            variants.push(ctx);
        }
    }
    variants.push("سلا".into());
    variants.push("لا".into());
    for v in &variants {
        for c in twine_text::shape(v).chars() {
            assert!(
                g.code_points.contains(&c),
                "{v:?}: U+{:04X} missing",
                u32::from(c)
            );
        }
    }
    assert!(g.code_points.contains(&')') && g.code_points.contains(&'('));

    // Montserrat has neither the forms nor (for `«`) a problem with the partner.
    let m = montserrat(12).chars_from("«").build().unwrap();
    assert!(m.warnings.is_empty(), "{:?}", m.warnings);
    assert!(m.code_points.contains(&'»'));
}

/// A subset font's glyphs are the full font's (same bitmaps, advances, boxes) and its line
/// metrics are unchanged, so swapping a full font for a subset changes no pixel of the text it
/// can draw.
#[test]
fn subset_glyphs_equal_the_full_font() {
    let full = dejavu().chars_from('\u{0590}'..='\u{05FF}').build().unwrap();
    let sub = dejavu().chars_from("שלום").build().unwrap();
    for c in "שלום".chars() {
        assert_eq!(glyph_of(&full, c), glyph_of(&sub, c), "{c}");
    }
    let lines = |g: &GeneratedFont| {
        (
            g.data.line_height,
            g.data.base_line,
            g.data.underline_position,
            g.data.underline_thickness,
        )
    };
    assert_eq!(lines(&full), lines(&sub));
    assert!(sub.flash_bytes < full.flash_bytes / 4);
}

#[test]
fn implied_chars_cover_shaping_and_mirroring() {
    let set: BTreeSet<char> = "\u{0644}\u{0627}[".chars().collect();
    let all = implied_chars(&set);
    // Lam-alef isolated and final ligatures, lam's and alef's own forms, the closing bracket.
    for c in [
        '\u{FEFB}', '\u{FEFC}', '\u{FEDD}', '\u{FEDE}', '\u{FEDF}', '\u{FEE0}', '\u{FE8D}', '\u{FE8E}', ']',
    ] {
        assert!(all.contains(&c), "U+{:04X}", u32::from(c));
    }
    assert!(set.is_subset(&all));
    // Nothing to add for plain Latin text.
    let latin: BTreeSet<char> = "Hello".chars().collect();
    assert_eq!(implied_chars(&latin), latin);
}

