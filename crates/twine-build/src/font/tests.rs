/// The rasterizer versions in the header are the ones the workspace builds with.
#[test]
fn rasterizer_versions_match_the_lock_file() {
    let lock = std::fs::read_to_string(root().join("Cargo.lock")).unwrap();
    let version = |name: &str| {
        let pat = format!("name = \"{name}\"\nversion = \"");
        let rest = &lock[lock.find(&pat).unwrap() + pat.len()..];
        rest[..rest.find('"').unwrap()].to_string()
    };
    for (name, text) in [
        ("fontdue", UNHINTED_RASTERIZER),
        ("skrifa", HINTED_RASTERIZER),
        ("ab_glyph_rasterizer", HINTED_RASTERIZER),
    ] {
        let v = version(name);
        let minor: String = v.split('.').take(2).collect::<Vec<_>>().join(".");
        assert!(text.contains(&format!("{name} {minor}")), "{name} {v}: {text}");
    }
}

/// R6.S03: every gamma table is monotonic and the identity at both ends, and the runtime's
/// shared tables are the generator's.
#[test]
fn gamma_tables_are_monotonic_with_identity_ends() {
    assert_eq!(Gamma::DEFAULT.tables(), twine_text::gamma::DEFAULT);
    assert_eq!(Gamma::LINEAR.tables(), twine_text::gamma::LINEAR);
    for centi in Gamma::MIN..=Gamma::MAX {
        let t = Gamma::table(centi);
        assert_eq!((t[0], t[15]), (0, 255), "{centi}");
        assert!(t.windows(2).all(|w| w[0] <= w[1]), "{centi}: {t:?}");
        if centi > 100 {
            assert!(
                t[1..15]
                    .iter()
                    .zip(Gamma::table(100)[1..15].iter())
                    .all(|(a, l)| a >= l)
            );
        }
    }
}

#[test]
fn gamma_and_hinting_options_parse_and_check() {
    assert_eq!("1.25,2".parse::<Gamma>(), Ok(Gamma::new(125, 200)));
    assert_eq!("default".parse::<Gamma>(), Ok(Gamma::DEFAULT));
    for bad in ["", "1.2", "1.234,2", "a,b", ",2", "1.2;1.8"] {
        assert!(bad.parse::<Gamma>().is_err(), "{bad:?}");
    }
    for g in [Gamma::LINEAR, Gamma::DEFAULT, Gamma::new(75, 250)] {
        assert_eq!(g.arg().parse::<Gamma>(), Ok(g));
    }
    for h in Hinting::ALL {
        assert_eq!(h.name().parse::<Hinting>(), Ok(h));
    }
    assert!("strong".parse::<Hinting>().is_err());
    let e = montserrat(12).gamma(Gamma::new(40, 180)).build().unwrap_err();
    assert!(e.message().contains("0.40"), "{e}");
    assert!(montserrat(12).gamma(Gamma::new(120, 401)).build().is_err());
}

/// Hinted subpixel fonts keep the subpixel grid alignment and their symbols.
#[test]
fn hinted_subpixel_fonts_generate() {
    for subpx in [Subpx::Hor, Subpx::Ver] {
        let g = montserrat(14)
            .subpx(subpx)
            .symbol_fonts(["assets/fonts/fa-solid-900.ttf", "assets/fonts/fa-brands-400.ttf"])
            .build()
            .unwrap();
        let font = load_generated_for_test(&g.data);
        let (_, info) = font.glyph('l', None).unwrap();
        match subpx {
            Subpx::Hor => assert_eq!(info.box_w % 3, 0),
            _ => assert_eq!(info.box_h % 3, 0),
        }
        assert!(info.adv_w % 16 == 0, "hinted advance");
    }
}
