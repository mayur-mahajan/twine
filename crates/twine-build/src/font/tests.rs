#[test]
fn symbols_are_merged_and_centered() {
    let g = montserrat(14)
        .symbol_fonts(["assets/fonts/fa-solid-900.ttf", "assets/fonts/fa-brands-400.ttf"])
        .build()
        .unwrap();
    assert!(g.source.contains("// Symbols: fa-solid-900.ttf SHA-256 "));
    let font = load_generated_for_test(&g.data);
    for c in twine_text::Symbol::ALL
        .iter()
        .filter(|s| s.is_font_awesome())
        .map(|s| s.as_char())
    {
        let (_, info) = font.glyph(c, None).unwrap();
        assert!(info.box_h > 0, "{c:?}");
        // Centered on the line box [-base_line, line_height - base_line].
        let center2 = 2 * i32::from(info.ofs_y) + i32::from(info.box_h);
        let line_center2 = i32::from(font.line_height) - 2 * i32::from(font.base_line);
        assert!(
            (center2 - line_center2).abs() <= 1,
            "{c:?}: {center2} vs {line_center2}"
        );
    }
}

