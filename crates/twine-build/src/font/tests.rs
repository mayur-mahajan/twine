/// Glyph subsetting: a font built from a translation catalog and the application's string
/// literals holds exactly their characters (plus the ones asked for explicitly).
#[test]
fn subset_from_catalog_and_rust_sources() {
    let dir = temp_dir("subset");
    std::fs::write(
        dir.join("main.rs"),
        "fn main() { label(\"Volume\"); let c = 'ä'; } // \"Zzz\"",
    )
    .unwrap();
    let catalog = crate::i18n::Translations::new()
        .source("en", crate::i18n::Format::Toml, "hello = \"Hi {name}\"")
        .source("de", crate::i18n::Format::Toml, "hello = \"Grüß {name}\"")
        .default_language("en")
        .build()
        .unwrap();
    let g = Font::from_ttf(root().join("assets/fonts/Montserrat-Medium.ttf"))
        .chars_from(&catalog)
        .chars_from_rust_sources(&dir)
        .chars_from('0'..='1')
        .build()
        .unwrap();
    let got: String = g.code_points[1..].iter().collect();
    // The catalog also gives the characters its numbers are written with (digits,
    // separators, minus and percent signs; German writes `12\u{A0}%`).
    assert_eq!(got, " %,-.0123456789GHVeilmoru\u{A0}ßäü");
    assert!(g.inputs.contains(&dir.join("main.rs")), "{:?}", g.inputs);
    let _ = std::fs::remove_dir_all(&dir);
}

/// The bitmap bytes and metrics of glyph `c` of `g`.
fn glyph_of(g: &GeneratedFont, c: char) -> (Vec<u8>, (u16, u8, u8, i8, i8)) {
    let id = g.code_points.iter().position(|&x| x == c).unwrap();
    let d = &g.data.glyphs[id];
    let end = g
        .data
        .glyphs
        .get(id + 1)
        .map_or(g.data.bitmap.len(), |n| n.bitmap_index as usize);
    (
        g.data.bitmap[d.bitmap_index as usize..end].to_vec(),
        (d.adv_w, d.box_w, d.box_h, d.ofs_x, d.ofs_y),
    )
}

