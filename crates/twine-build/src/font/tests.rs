/// The inked columns of the row through the middle of `c`'s stems (a quarter up its box), as
/// A8 coverage of the generated font.
fn stem_row(g: &GeneratedFont, c: char) -> Vec<u8> {
    let font = load_generated_for_test(&g.data);
    let (_, info) = font.glyph(c, None).unwrap();
    let (w, h) = (usize::from(info.box_w), usize::from(info.box_h));
    let mut out = vec![0u8; w * h];
    assert!(
        font.provider
            .render_a8(&info, Polarity::DarkOnLight, &mut out, &mut GlyphCache::new(0))
    );
    let row = h - 1 - h / 4;
    out[row * w..(row + 1) * w].to_vec()
}

/// R6.S03: full hinting puts the vertical stems of the bundled fonts on whole pixels at
/// 10–16 px — one column at (almost) full ink — where unhinted stems straddle two columns.
#[test]
fn hinted_stems_land_on_whole_pixels() {
    let mut soft = 0;
    for ttf in [
        "assets/fonts/Montserrat-Medium.ttf",
        "assets/fonts/DejaVuSans.ttf",
    ] {
        for size in [10u16, 12, 14, 16] {
            let font = |h: Hinting| {
                Font::from_ttf(ttf)
                    .root(root())
                    .size(size)
                    .chars_from("lIH")
                    .hinting(h)
                    .gamma(Gamma::LINEAR)
                    .name("STEMS")
                    .crate_path("twine_text")
                    .build()
                    .unwrap()
            };
            let (full, none) = (font(Hinting::Full), font(Hinting::None));
            for c in ['l', 'I', 'H'] {
                let hinted = stem_row(&full, c);
                // At least 90 % ink: a stem thinner than a pixel (DejaVu at 10 px) fills one
                // column almost completely.
                assert!(
                    hinted.iter().any(|&v| v >= 230),
                    "{ttf} {size} px {c:?}: a stem column at full ink, got {hinted:?}"
                );
                if !stem_row(&none, c).iter().any(|&v| v >= 230) {
                    soft += 1;
                }
            }
        }
    }
    // Unhinted, most of these stems straddle two columns (Montserrat 14 px `l`: 73 % / 62 %).
    assert!(soft >= 12, "unhinted stems without a full column: {soft}");
}

/// R6.S03: light (vertical-only) hinting keeps the unhinted advances and kerning, so the
/// layout of text does not change; full hinting rounds advances to whole pixels.
#[test]
fn light_hinting_keeps_advances_and_kerning() {
    let build = |h: Hinting| montserrat(14).hinting(h).build().unwrap();
    let (none, light, full) = (build(Hinting::None), build(Hinting::Light), build(Hinting::Full));
    let adv = |g: &GeneratedFont| g.data.glyphs.iter().map(|d| d.adv_w).collect::<Vec<_>>();
    assert_eq!(adv(&light), adv(&none));
    assert_eq!(light.data.kern, none.data.kern);
    assert_eq!(
        full.data.kern, none.data.kern,
        "kerning comes from GPOS, not the hinter"
    );
    assert!(
        full.data.glyphs[1..].iter().all(|d| d.adv_w % 16 == 0),
        "full hinting: whole-pixel advances"
    );
    assert_ne!(adv(&full), adv(&none));
}

/// The header records the hinting mode with the rasterizer versions and the text gamma;
/// non-default options appear in the command line.
